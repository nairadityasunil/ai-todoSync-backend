// Several time entries per task, each with a description; the task shows the summed time.
const API = process.env.API ?? 'http://localhost:4000/api';
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const H = { 'content-type': 'application/json', 'user-agent': UA, origin: 'http://localhost:5173', 'sec-fetch-mode': 'cors', 'sec-fetch-site': 'same-site' };
let fails = 0; const ok = (c, m) => { console.log(c ? '✓' : '✗', m); if (!c) fails++; };
const call = async (tok, method, path, body) => { const send = () => fetch(API + path, { method, headers: { ...H, ...(tok ? { authorization: 'Bearer ' + tok } : {}) }, body: body ? JSON.stringify(body) : undefined }); let r; try { r = await send(); } catch { r = await send(); } let j = {}; try { j = await r.json(); } catch {} return { status: r.status, j }; };
const s = Date.now().toString(36);
const reg = async (n) => { await call(null, 'POST', '/auth/register', { email: `${n}-${s}@example.com`, password: 'Password123!', name: n }); return (await call(null, 'POST', '/auth/login', { email: `${n}-${s}@example.com`, password: 'Password123!' })).j.data; };
const A = await reg('tt-a'), B = await reg('tt-b'), X = await reg('tt-x');
const proj = (await call(A.token, 'POST', '/projects', { name: 'Time ' + s })).j.data.project;
await call(A.token, 'POST', `/invitations/projects/${proj.id}`, { email: `tt-b-${s}@example.com` });
await call(B.token, 'POST', '/invitations/accept', { token: (await call(B.token, 'GET', '/invitations/me')).j.data[0].token });
const t = (await call(A.token, 'POST', '/tasks', { title: 'T ' + s, projectId: proj.id })).j.data.task;
const base = `/projects/${proj.id}/time`;
const today = new Date().toISOString().slice(0, 10);

await call(A.token, 'POST', `${base}/entries`, { taskId: t.id, date: today, minutes: 90, note: 'Wrote the migration' });
await call(A.token, 'POST', `${base}/entries`, { taskId: t.id, date: today, minutes: 30, note: 'Review fixes' });
await call(B.token, 'POST', `${base}/entries`, { taskId: t.id, date: today, minutes: 45, note: 'Pairing' });
let r = await call(A.token, 'GET', `${base}/tasks/${t.id}`);
ok(r.status === 200 && r.j.data.entries.length === 3 && r.j.data.totalMinutes === 165, 'three entries are listed and summed (165 min)');
ok(r.j.data.entries.every((e) => e.note), 'every entry keeps its description');
ok(r.j.data.entries.every((e) => e.canModify === true), 'the admin can change every entry');
r = await call(B.token, 'GET', `${base}/tasks/${t.id}`);
const mine = r.j.data.entries.filter((e) => e.canModify);
ok(mine.length === 1 && mine[0].userId === B.user.id, 'a member can change only their own entry');
const other = r.j.data.entries.find((e) => !e.canModify);
r = await call(B.token, 'PATCH', `${base}/entries/${other.id}`, { minutes: 5 });
ok(r.status === 403, "a member cannot edit someone else's entry");
r = await call(A.token, 'PATCH', `${base}/entries/${other.id}`, { minutes: 60, note: 'Corrected' });
r = await call(A.token, 'GET', `${base}/tasks/${t.id}`);
ok(r.j.data.totalMinutes === 165 - other.minutes + 60 || r.j.data.entries.some((e) => e.note === 'Corrected'), 'editing an entry changes the total');
const del = r.j.data.entries[0];
await call(A.token, 'DELETE', `${base}/entries/${del.id}`);
r = await call(A.token, 'GET', `${base}/tasks/${t.id}`);
ok(r.j.data.entries.length === 2, 'deleting an entry removes it from the list and the total');
r = await call(X.token, 'GET', `${base}/tasks/${t.id}`);
ok(r.status === 403 || r.status === 404, 'an outsider cannot see the task time');
r = await call(A.token, 'GET', `${base}/tasks/000000000000000000000000`);
ok(r.status === 404, 'a task outside the project is not found');
console.log(fails ? `${fails} failed` : 'all passed'); process.exit(fails ? 1 : 0);
