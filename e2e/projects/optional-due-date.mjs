// The due date is optional: none by default, settable and clearable, and bad values are refused.
const API = process.env.API ?? 'http://localhost:4000/api';
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const H = { 'content-type': 'application/json', 'user-agent': UA, origin: 'http://localhost:5173', 'sec-fetch-mode': 'cors', 'sec-fetch-site': 'same-site' };
let fails = 0; const ok = (c, m) => { console.log(c ? '✓' : '✗', m); if (!c) fails++; };
const L = await (await fetch(API + '/auth/login', { method: 'POST', headers: H, body: JSON.stringify({ email: 'qa@example.com', password: 'Password123!' }) })).json();
const call = async (method, path, body) => { const r = await fetch(API + path, { method, headers: { ...H, authorization: 'Bearer ' + L.data.token }, body: body ? JSON.stringify(body) : undefined }); let j = {}; try { j = await r.json(); } catch {} return { status: r.status, j }; };
const s = Date.now().toString(36);
let r = await call('POST', '/tasks', { title: 'No due ' + s });
ok(r.status === 201 && r.j.data.task.date === null, 'a task can be created with no due date (date is null)');
const id = r.j.data.task.id;
ok((await call('POST', '/tasks', { title: 'Empty ' + s, date: '' })).j.data.task.date === null, 'an empty date means no due date');
r = await call('POST', '/tasks', { title: 'Due ' + s, date: '2026-12-01' });
ok(r.status === 201 && r.j.data.task.date === '2026-12-01', 'a due date can be set on creation');
ok((await call('POST', '/tasks', { title: 'Bad ' + s, date: 'tomorrow' })).status === 400, 'a malformed due date is refused');
ok((await call('POST', '/tasks', { date: '2026-12-01' })).status === 400, 'a title is still required');
r = await call('PATCH', `/tasks/${id}`, { date: '2026-12-24' });
ok(r.status === 200 && r.j.data.task.date === '2026-12-24', 'a due date can be added later');
r = await call('PATCH', `/tasks/${id}`, { date: null });
ok(r.status === 200 && r.j.data.task.date === null, 'and removed again');
ok((await call('PATCH', `/tasks/${id}`, { date: 'soon' })).status === 400, 'a malformed date on update is refused');
const list = (await call('GET', '/tasks')).j.data.tasks;
ok(list.some((t) => t.id === id) && list.every((t) => t.date === null || /^\d{4}-\d{2}-\d{2}$/.test(t.date)), 'lists include tasks with no due date');
ok((await call('GET', '/tasks/overdue-nope')).status !== 500, 'nothing breaks on tasks without a date');
console.log(fails ? `\n${fails} FAILED` : '\nall passed'); process.exit(fails ? 1 : 0);
